// Dependency license check. Walks every production dependency (direct and transitive),
// fails on licenses outside the allowlist, and writes THIRD_PARTY_LICENSES.md.
// Usage: npm run licenses
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const ALLOWED = new Set(["MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "0BSD", "OFL-1.1", "MPL-2.0", "Unlicense", "CC0-1.0", "BlueOak-1.0.0", "Python-2.0", "W3C-20150513"]);

const USE = {
  mermaid: "Parsing and rendering diagrams in the browser",
  dompurify: "Sanitizing rendered SVG (also bundled by Mermaid)",
  lucide: "Interface icons",
  "@fontsource-variable/space-grotesk": "Heading typeface (self-hosted)",
};

// Reviewed by hand: weak-copyleft components that ship unmodified and keep their own license.
const REVIEWED = {
  elkjs: "EPL-2.0 (weak copyleft). Bundled unmodified inside Mermaid's distribution for the optional ELK layout. Source: https://github.com/kieler/elkjs",
};

/** When package.json has no license field, read the license file's first line. */
function licenseFromFile(dir) {
  const file = readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
  if (!file) return "UNKNOWN";
  const head = readFileSync(join(dir, file), "utf8").slice(0, 200);
  if (/MIT License/i.test(head)) return "MIT";
  if (/ISC License/i.test(head)) return "ISC";
  if (/Apache License/i.test(head)) return "Apache-2.0";
  return "UNKNOWN";
}

// An SPDX "A OR B" expression is fine if any option is allowed; "A AND B" needs all.
function acceptable(expr) {
  const clean = expr.replace(/[()]/g, "").trim();
  if (clean.includes(" OR ")) return clean.split(" OR ").some((p) => acceptable(p));
  if (clean.includes(" AND ")) return clean.split(" AND ").every((p) => acceptable(p));
  return ALLOWED.has(clean);
}

const tree = JSON.parse(execFileSync("npm", ["ls", "--omit=dev", "--all", "--json", "--long"], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));
const direct = new Set(Object.keys(JSON.parse(readFileSync(join(root, "package.json"), "utf8")).dependencies ?? {}));
const packages = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    const key = `${name}@${info.version}`;
    if (packages.has(key) || !info.path) continue;
    const pkg = JSON.parse(readFileSync(join(info.path, "package.json"), "utf8"));
    const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type
      ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join(" OR ") : existsSync(info.path) ? licenseFromFile(info.path) : "UNKNOWN");
    const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? "";
    packages.set(key, { name, version: info.version, license, repo: repo.replace(/^git\+/, "").replace(/\.git$/, ""), direct: direct.has(name) });
    walk(info.dependencies);
  }
})(tree.dependencies);

const rows = [...packages.values()].sort((a, b) => Number(b.direct) - Number(a.direct) || a.name.localeCompare(b.name));
const bad = rows.filter((r) => !acceptable(r.license) && !REVIEWED[r.name]);
const counts = rows.reduce((m, r) => m.set(r.license, (m.get(r.license) ?? 0) + 1), new Map());

const md = `# Third-party licenses

Diagram Studio is MIT licensed. It ships the open-source packages below, served to the browser from \`node_modules\`
or used by the server. This file is generated by \`npm run licenses\`, which also fails if any production dependency
uses a license outside the project's allowlist (permissive licenses, MPL-2.0 for unmodified files, OFL-1.1 for fonts).

## Direct dependencies

| Package | Version | License | Used for |
|---|---|---|---|
${rows.filter((r) => r.direct).map((r) => `| [${r.name}](${r.repo}) | ${r.version} | ${r.license} | ${USE[r.name] ?? ""} |`).join("\n")}

Development only (not shipped): [playwright-core](https://github.com/microsoft/playwright), Apache-2.0, for the end-to-end screenshot run.
Icons are from Lucide (ISC). The Space Grotesk typeface is by Florian Karsten, licensed under the SIL Open Font License 1.1.

## Reviewed exceptions

${Object.entries(REVIEWED).map(([n, why]) => `- **${n}**: ${why}`).join("\n")}

## All production packages (${rows.length}, including transitive)

License summary: ${[...counts].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ")}.

| Package | Version | License |
|---|---|---|
${rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`).join("\n")}

The full license texts are included in each package's directory under \`node_modules/\`.
`;

writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), md);
console.log(`${rows.length} production packages checked. Licenses: ${[...counts].map(([l, n]) => `${l}=${n}`).join(", ")}`);
if (bad.length) {
  console.error(`✖ Not on the allowlist:\n${bad.map((r) => `  ${r.name}@${r.version}: ${r.license}`).join("\n")}`);
  process.exit(1);
}
console.log("✔ all licenses are on the allowlist; wrote THIRD_PARTY_LICENSES.md");
